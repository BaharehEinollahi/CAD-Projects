`timescale 1ns / 1ps

module midterm_testcase;

    reg clk;
    reg rst;
    reg start;
    reg [7:0] a0, w0, a1, w1;

    wire ready;
    wire [15:0] result;

    vector_mult_top uut (
        .clk(clk),
        .rst(rst),
        .start(start),
        .a0(a0),
        .w0(w0),
        .a1(a1),
        .w1(w1),
        .result(result),
        .ready(ready)
    );

    always #5 clk = ~clk;

    task run_test;
        input [7:0] ta0, tw0, ta1, tw1;
        input [15:0] expected;
        begin
            #10
            rst = 1;
            #20 rst = 0;
            #10;
            a0 = ta0; w0 = tw0;
            a1 = ta1; w1 = tw1;
            start = 1;
            #10 start = 0;
            wait(ready);
            if (result === expected)
                $display("PASS: a0=%b w0=%b a1=%b w1=%b -> result=%b ✅", ta0, tw0, ta1, tw1, result);
            else
                $display("FAIL: a0=%b w0=%b a1=%b w1=%b -> got=%b expected=%b ❌",
                         ta0, tw0, ta1, tw1, result, expected);
        end
    endtask

    initial begin
        clk = 0;
        rst = 1;
        start = 0;
        a0 = 0; w0 = 0; a1 = 0; w1 = 0;
        #20 rst = 0;

        run_test(8'b00100010, 8'b01110010, 8'b00011001, 8'b01100010, 16'b0001100010110110);
        run_test(8'b10010010, 8'b00101010, 8'b00001110, 8'b00000000, 16'b0001011111110100);
        run_test(8'b01101001, 8'b00000000, 8'b01001100, 8'b00111111, 16'b0001001010110100);
        run_test(8'b00000000, 8'b01111111, 8'b00011001, 8'b01010111, 16'b0000100001111111);
        run_test(8'b11110101, 8'b00010011, 8'b00000000, 8'b00101101, 16'b0001001000101111);
        run_test(8'b11111111, 8'b01001100, 8'b00000001, 8'b00101101, 16'b0100101111100001);
        run_test(8'b00000001, 8'b00100000, 8'b11111111, 8'b01011001, 16'b0101100011000111);
        run_test(8'b00000000, 8'b00000000, 8'b00000000, 8'b00000000, 16'b0000000000000000);
        run_test(8'b11111111, 8'b11111111, 8'b00000101, 8'b00000010, 16'b1111111000001011);
        run_test(8'b11111111, 8'b11111111, 8'b11111111, 8'b00000010, 16'b1111111111111111);
        run_test(8'b10000000, 8'b10000000, 8'b10000000, 8'b10000000, 16'b1000000000000000);
        run_test(8'b11111111, 8'b10000000, 8'b01111111, 8'b00000001, 16'b0111111111111111);
        run_test(8'b11111111, 8'b10000000, 8'b10000001, 8'b00000001, 16'b1000000000000001);
        run_test(8'b10101010, 8'b01010101, 8'b01010101, 8'b10101010, 16'b0111000011100100);
        run_test(8'b00000001, 8'b00000001, 8'b00000000, 8'b00000000, 16'b0000000000000001);
        run_test(8'b11111111, 8'b00000000, 8'b00000000, 8'b11111111, 16'b0000000000000000);
        run_test(8'b11001000, 8'b01111011, 8'b01100100, 8'b11001000, 16'b1010111000111000);
        run_test(8'b01001001, 8'b11010011, 8'b00010011, 8'b11101001, 16'b0100110101110110);
        run_test(8'b11111111, 8'b11111111, 8'b11111111, 8'b00000001, 16'b1111111100000000);
        run_test(8'b11111111, 8'b01100100, 8'b11111111, 8'b01100100, 16'b1100011100111000);
        run_test(8'b00000101, 8'b11111111, 8'b11111111, 8'b00000101, 16'b0000100111110110);

        $display("✅ All tests completed.");
        $finish;
    end

endmodule
